export const messages: Record<ResolvedLanguage, Record<MessageKey, string>> = { en, zh };

/** Languages offered in settings, in display order. */
export const UI_LANGUAGES: UiLanguage[] = ["auto", "en", "zh"];

export function resolveUiLanguage(setting: UiLanguage | undefined, obsidianLanguage: string): ResolvedLanguage {
    if (setting === "en" || setting === "zh") return setting;
    return String(obsidianLanguage || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function resolveUiLocale(language: ResolvedLanguage): string {
    return language === "zh" ? "zh-CN" : "en-US";
}

export function translate(language: ResolvedLanguage, key: MessageKey, params?: MessageParams): string {
    const template = messages[language][key] || messages.en[key] || key;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = params[name];
        return value === undefined || value === null ? match : String(value);
    });
}

/** Translate locally synthesized names without changing persisted identifiers. */
export function localizedProjectName(name: string, language: ResolvedLanguage): string {
    if (name === "收集箱") return translate(language, "common.inbox");
    if (name === "本地任务") return translate(language, "common.localProject");
    return name;
}

export type Translator = (key: MessageKey, params?: MessageParams) => string;

export function createTranslator(language: ResolvedLanguage): Translator {
    return (key, params) => translate(language, key, params);
}

/**
 * Translate with the default (English) locale. Only for UI that can be rendered
 * without a plugin instance; prefer `plugin.t()` everywhere else.
 */
export function translateDefault(key: MessageKey, params?: MessageParams): string {
    return translate("en", key, params);
}

export function formatNumber(value: number, language: ResolvedLanguage): string {
    return new Intl.NumberFormat(resolveUiLocale(language)).format(value);
}

/** `2026年9月14日` / `Sep 14, 2026` */
export function formatFullDate(date: Date, language: ResolvedLanguage): string {
    return new Intl.DateTimeFormat(resolveUiLocale(language), { year: "numeric", month: "short", day: "numeric" }).format(date);
}

/** `9月14日` / `Sep 14` */
export function formatMonthDay(date: Date, language: ResolvedLanguage): string {
    return new Intl.DateTimeFormat(resolveUiLocale(language), { month: "short", day: "numeric" }).format(date);
}

